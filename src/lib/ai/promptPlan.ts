import type { AiPlanKind } from "./types";

// PLAN_CONTEXT: Pro AI Plus / Maxで分析材料・分析思想を切り替える。
// Pro AI Plusはスポーツテストを前提とせず、それ単独で高品質な競技パフォーマンス分析に
// なるようにする(「Maxからスポーツテストを抜いただけ」にしない)。
export function buildPlanContext(planKind: AiPlanKind): string {
  if (planKind === "proAiPlus") {
    return `【このチームのプラン: Pro AI Plus】
「競技パフォーマンスを中心とした高度AI分析」を行います。

使用する分析材料: 選手基本情報、チーム基本情報、競技、学年、ポジション・役割、試合スタッツ、試合ごとの記録、スタッツ成長推移、身長・体重等の通常身体情報、練習履歴、練習メニュー、練習参加状況。

スポーツテストのデータは使用しません。スポーツテストのデータが存在しないことは正常な状態であり、欠陥ではありません。「スポーツテストのデータがないため分析できない」といった注意書きを出力する必要はありません。触れずに、上記の分析材料だけで競技パフォーマンス分析として完結させてください。`;
  }
  return `【このチームのプラン: Max】
「競技パフォーマンス×身体能力を横断した高度AI分析」を行います。

Pro AI Plusの全分析材料(選手基本情報、チーム基本情報、競技、学年、ポジション・役割、試合スタッツ、試合ごとの記録、スタッツ成長推移、身長・体重等の通常身体情報、練習履歴、練習メニュー、練習参加状況)に加えて、スポーツテスト・スポーツテストの時系列変化・身体能力変化を使用します。

競技パフォーマンス×身体能力×身体成長×練習×参加状況のクロス分析を重視してください。スポーツテストのデータが提供されていない場合は、Pro AI Plus相当の分析材料だけで完結させ、存在しないデータについて言及しないでください。`;
}
